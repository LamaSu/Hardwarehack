"""
8-channel medium fill for Studio45, as described by the team:

1. pick up a column of 8 tips from the 50 µL filter tip rack (A2)
2. aspirate medium from the 12-trough reservoir (B1)
3. dispense into the next free 8-well position of the 384-well PCR plate (B3)
4. home, then drop the tips in the trash (A3)

An 8-channel head spans every other row of a 384-well plate, so a column holds
two positions: A1 covers rows A, C, ... O and B1 covers rows B, D, ... P.
Positions run A1, B1, A2, B2, ... B24 (48 in total).
"""

API_LEVEL = "2.30"
POSITIONS = 48
TIP_COLUMNS = 12
MIN_VOLUME_UL = 5.0   # Flex 8-channel 1000 µL pipette minimum
MAX_VOLUME_UL = 50.0  # 50 µL filter tips

# Labware load names; check them against the physical deck.
TIPS_1000 = ("opentrons_flex_96_tiprack_1000ul", "A1")
TIPS_50_FILTER = ("opentrons_flex_96_filtertiprack_50ul", "A2")
RESERVOIR = ("nest_12_reservoir_15ml", "B1")
STOCK_PLATE = ("nest_96_wellplate_2ml_deep", "B2")
PCR_PLATE = ("biorad_384_wellplate_50ul", "B3")
TRASH_SLOT = "A3"
MEDIUM_TROUGH = "A1"


def well_for_position(position: int) -> str:
    """
    Top well of an 8-channel position on the 384-well plate (1-based).

    Raises
    ------
    ValueError
        If ``position`` is outside 1-48.
    """
    if not 1 <= position <= POSITIONS:
        raise ValueError(f"Position must be 1-{POSITIONS}, got {position}")
    column, offset = divmod(position - 1, 2)
    return f"{'AB'[offset]}{column + 1}"


def protocol_source(position: int, volume_ul: float = 50.0, tip_column: int = 1) -> str:
    """
    Python source of the medium fill protocol for one position.

    Parameters
    ----------
    position : int
        1-48, see ``well_for_position``.
    volume_ul : float, default=50
        Medium per well, 5-50 µL.
    tip_column : int, default=1
        Column of the 50 µL filter tip rack to use (1-12).

    Raises
    ------
    ValueError
        If any argument is out of range.
    """
    well = well_for_position(position)
    if not 1 <= tip_column <= TIP_COLUMNS:
        raise ValueError(f"Tip column must be 1-{TIP_COLUMNS}, got {tip_column}")
    if volume_ul > MAX_VOLUME_UL:
        raise ValueError(f"Volume must be at most {MAX_VOLUME_UL:g} µL (50 µL filter tips)")
    if volume_ul < MIN_VOLUME_UL:
        raise ValueError(f"Volume must be at least {MIN_VOLUME_UL:g} µL (pipette minimum)")
    return f'''"""
Medium fill: 8 x {volume_ul:g} µL into 384-well position {well} (rows {"A,C,...,O" if well[0] == "A" else "B,D,...,P"}).

Generated by drug-screen-platform. Deck: 1000 µL tips A1, 50 µL filter tips A2,
12-trough reservoir B1 (medium in trough {MEDIUM_TROUGH[1:]}), stock plate B2, 384-well PCR plate B3, trash A3.
"""

requirements = {{"robotType": "Flex", "apiLevel": "{API_LEVEL}"}}
metadata = {{"protocolName": "Medium fill {well}", "author": "drug-screen-platform"}}

VOLUME_UL = {volume_ul!r}
TIP_COLUMN = {tip_column!r}
DESTINATION = {well!r}


def run(protocol):
    protocol.load_trash_bin({TRASH_SLOT!r})
    protocol.load_labware(*{TIPS_1000!r})
    tips = protocol.load_labware(*{TIPS_50_FILTER!r})
    reservoir = protocol.load_labware(*{RESERVOIR!r})
    protocol.load_labware(*{STOCK_PLATE!r})
    plate = protocol.load_labware(*{PCR_PLATE!r})
    pipette = protocol.load_instrument("flex_8channel_1000", "left")

    pipette.pick_up_tip(tips[f"A{{TIP_COLUMN}}"])
    pipette.aspirate(VOLUME_UL, reservoir[{MEDIUM_TROUGH!r}])
    pipette.dispense(VOLUME_UL, plate[DESTINATION])
    protocol.home()
    pipette.drop_tip()
'''
